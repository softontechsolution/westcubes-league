# MATCH SCHEMA (Data Validation)
# This section defines the exact blueprint of the data we expect from 
# the frontend when recording a new match. 
# =====================================================================
class MatchCreate(BaseModel):
    home_team_id: int
    away_team_id: int
    home_goals: int
    away_goals: int

# =====================================================================
# MATCH ENDPOINT (Business Logic)
# This section handles the POST request to save a completed match into
# the database securely.
# =====================================================================
@app.post("/matches/")
def record_match(match: MatchCreate, db: Session = Depends(get_db)):
    
    # 1. Validate that the match makes logical sense
    if match.home_team_id == match.away_team_id:
        raise HTTPException(status_code=400, detail="A team cannot play against itself.")
    
    # 2. Prepare the data for the database using our SQLAlchemy model
    new_match = models.Match(
        home_team_id=match.home_team_id,
        away_team_id=match.away_team_id,
        home_goals=match.home_goals,
        away_goals=match.away_goals
    )
    
    # 3. Stage, commit, and refresh the database transaction
    db.add(new_match)
    db.commit()
    db.refresh(new_match)
    
    # 4. Return the successfully saved database record back to the frontend
    return new_match

# =====================================================================
# STANDINGS ENDPOINT (Business Logic & Data Aggregation)
# This section calculates the entire league table dynamically based on
# the raw match data stored in the database.
# =====================================================================
@app.get("/standings/")
def get_standings(db: Session = Depends(get_db)):
    # 1. Fetch raw data from the database
    teams = db.query(models.Team).all()
    matches = db.query(models.Match).all()
    
    # 2. Initialize a dictionary to hold calculated stats for each team
    # Using team_id as the key for lightning-fast lookups
    standings_data = {
        team.id: {
            "id": team.id,
            "name": team.name,
            "played": 0, "won": 0, "drawn": 0, "lost": 0,
            "goalsFor": 0, "goalsAgainst": 0, "goalDifference": 0, "points": 0
        } for team in teams
    }
    
    # 3. Process every match to calculate wins, losses, and goals
    for match in matches:
        home = standings_data.get(match.home_team_id)
        away = standings_data.get(match.away_team_id)
        
        # Skip if a team was deleted but the match still exists
        if not home or not away: 
            continue
            
        # Update Matches Played
        home["played"] += 1
        away["played"] += 1
        
        # Update Goals Scored and Conceded
        home["goalsFor"] += match.home_goals
        home["goalsAgainst"] += match.away_goals
        away["goalsFor"] += match.away_goals
        away["goalsAgainst"] += match.home_goals
        
        # Determine the winner and distribute points
        if match.home_goals > match.away_goals:
            home["won"] += 1
            home["points"] += 3
            away["lost"] += 1
        elif match.home_goals < match.away_goals:
            away["won"] += 1
            away["points"] += 3
            home["lost"] += 1
        else:
            home["drawn"] += 1
            home["points"] += 1
            away["drawn"] += 1
            away["points"] += 1
            
    # 4. Calculate Goal Difference and sort the final table
    for stats in standings_data.values():
        stats["goalDifference"] = stats["goalsFor"] - stats["goalsAgainst"]
        
    # Sort mathematically: Priority 1: Points, Priority 2: Goal Diff, Priority 3: Goals For
    sorted_standings = sorted(
        standings_data.values(), 
        key=lambda x: (x["points"], x["goalDifference"], x["goalsFor"]), 
        reverse=True
    )
    
    return sorted_standings

