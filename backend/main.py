# GET PLAYERS BY TEAM ENDPOINT
# Fetches players specifically linked to a given team_id.
# =====================================================================
@app.get("/teams/{team_id}/players/")
def get_players_by_team(team_id: int, db: Session = Depends(get_db)):
    # 1. Query the Player table specifically for the requested team_id
    # We use .filter() here instead of fetching all players and filtering in Python.
    # This is highly efficient because the database engine does the work,
    # minimizing memory usage in our Python application.
    players = db.query(models.Player).filter(models.Player.team_id == team_id).all()
    
    # 2. Return the filtered list
    return players

# =====================================================================
# GET MATCH HISTORY BY TEAM ENDPOINT
# Fetches all matches where the specific team played (Home or Away).
# =====================================================================
@app.get("/teams/{team_id}/matches/")
def get_matches_by_team(team_id: int, db: Session = Depends(get_db)):
    # Efficiently query matches where team_id matches home OR away.
    # The database executes this as a single indexed query.
    matches = db.query(models.Match).filter(
        or_(
            models.Match.home_team_id == team_id,
            models.Match.away_team_id == team_id
        )
    ).all()
    return matches

