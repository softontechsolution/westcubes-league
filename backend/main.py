# Pydantic schemas for partial updates
class TeamUpdate(BaseModel):
    name: Optional[str] = None
    manager_name: Optional[str] = None

@app.patch("/teams/{team_id}")
def update_team(team_id: int, team_update: TeamUpdate, db: Session = Depends(get_db)):
    # 1. Fetch existing record
    db_team = db.query(models.Team).filter(models.Team.id == team_id).first()
    if not db_team:
        raise HTTPException(status_code=404, detail="Team not found")

    # 2. Update fields only if they are provided in the request
    if team_update.name:
        db_team.name = team_update.name
    if team_update.manager_name:
        db_team.manager_name = team_update.manager_name

    db.commit()
    db.refresh(db_team)
    return db_team